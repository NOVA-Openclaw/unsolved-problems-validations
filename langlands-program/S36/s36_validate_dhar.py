#!/usr/bin/env python3
"""S36 VALIDATE — Dhar, arXiv:2608.04674v1, "On Tate cohomology and base change of
representations of D^x".  Finite/brute-force checks of the load-bearing steps of Thm 1.1/3.4.

Level-zero model: K^x / U^1_K = <varpi> x k_K^x, k_K = F_{q^f}, cyclic of order M = q^f - 1.
A tame character theta is determined (on the part Galois acts on) by an integer a mod M:
theta(g^i) = zeta_M^(a*i), g a generator of k_K^x.  Gal(K/F) acts through x -> x^q.

Checks
 C1  Lemma 2.1 (admissibility of (EK/E, theta o Nr)) — paper asserts it without argument.
     Brute-force over (q, f, ell, E/F unramified | tamely totally ramified).
 C2  Mackey step: |W_K \\ W_F / W_E| = [K cap E : F] = 1 when gcd(f, ell) = 1.
 C3  Frobenius-twist step: Lambda_E|_J = Lambda^ell, via Nr_{F_{q^{f ell}}/F_{q^f}}(x) = x^ell on F_{q^f}
     (exponent identity (q^{f ell}-1)/(q^f-1) == ell mod (q^f - 1)).
 C4  Tate cohomology of a rank-1 O_K-line with trivial sigma: H^0 = O/ell, H^1 = 0.
 C5  Lemma 3.2 uniqueness: T' = c T with c^ell = 1.  For ell = 2, c = -1 is available in any field;
     with sigma acting by -1 the Tate groups SWAP (H^0 = 0, H^1 = O/2).  Checked on Z_(2)-lattice models.
"""
from math import gcd
import itertools, sys

primes = [2, 3, 5, 7, 11, 13]

def is_admissible(a, M, frob, order):
    """(K/F,theta) admissible <=> theta^gamma != theta for all nontrivial gamma in cyclic group
    generated by x->x^frob of given order.  On exponents: a*frob^j != a (mod M) for 0<j<order."""
    return all((a * pow(frob, j, M) - a) % M != 0 for j in range(1, order))

def c1():
    checked = fails = 0
    examples = []
    for p in [2, 3, 5, 7]:
        for r in [1, 2]:
            q = p ** r
            for f in range(1, 7):
                M = q ** f - 1
                if M > 20000:
                    continue
                for ell in primes:
                    if ell == p or f % ell == 0:
                        continue  # need ell != p and ell not | f (f | d, ell not | d)
                    cases = [("unram", None)]
                    if (q - 1) % ell == 0:
                        cases.append(("ram", None))  # tame totally ramified Galois deg ell needs mu_ell in F
                    for kind, _ in cases:
                        for a in range(M):
                            if not is_admissible(a, M, q, f):
                                continue
                            if kind == "unram":
                                # EK = F_{q^{f ell}}; Nr on residue is identity on exponents (N(G)=g);
                                # Gal(EK/E) generated by x->x^{q^ell}, order f; residue char exponent a mod M
                                # viewed on k_EK: G^i -> zeta_M^{a i}; conj by q^ell acts i->q^ell i mod M'
                                # which reduces mod M to multiplication by q^ell.
                                a_t, frob_t = a, pow(q, ell, M)
                            else:
                                # EK/K totally ramified: same residue field; Nr on residue units is x^ell;
                                # Gal(EK/E) ~ Gal(k_K/k_F), frob x->x^q.
                                a_t, frob_t = (a * ell) % M, q
                            checked += 1
                            if not is_admissible(a_t, M, frob_t, f):
                                fails += 1
                                if len(examples) < 5:
                                    examples.append((q, f, ell, kind, a))
    return checked, fails, examples

def c2():
    bad = [(f, ell) for f in range(1, 50) for ell in primes if f % ell != 0 and gcd(f, ell) != 1]
    return bad

def c3():
    bad = []
    for q in [2, 3, 4, 5, 7, 8, 9, 11, 13]:
        for f in range(1, 6):
            for ell in primes:
                M = q ** f - 1
                e = (q ** (f * ell) - 1) // (q ** f - 1)
                if (e - ell) % M != 0:
                    bad.append((q, f, ell))
    return bad

def tate_exact(s, ell):
    """Exact Tate cohomology of a free rank-1 Z_(ell)-module with sigma acting by s in {+1,-1},
    s^ell = 1.  Over a torsion-free rank-1 module, x -> m*x has kernel 0 unless m == 0, and
    cokernel of order ell^{v_ell(m)} (0 -> whole module, 'inf').  Returns (H^0, H^1) as strings."""
    assert pow(s, ell) == 1
    one_minus = 1 - s
    nr = sum(s ** k for k in range(ell))
    def v(m):
        if m == 0: return None
        k = 0
        while m % ell == 0: m //= ell; k += 1
        return k
    # H^0 = ker(1-s)/im(Nr);  H^1 = ker(Nr)/im(1-s)
    h0 = ("O/ell^%d" % v(nr)) if one_minus == 0 else "0"
    h1 = ("O/ell^%d" % v(one_minus)) if nr == 0 else "0"
    return h0.replace("O/ell^0", "0"), h1.replace("O/ell^0", "0")

def c4c5():
    out = {}
    for ell in [2, 3, 5, 7]:
        out[(ell, +1)] = tate_exact(+1, ell)
    out[(2, -1)] = tate_exact(-1, 2)          # only ell = 2 admits c = -1 with c^ell = 1 in Q_2
    return out

def c5_roots_of_unity():
    """mu_ell in K = Q_ell^ur ?  Q_ell(zeta_ell)/Q_ell is totally ramified of degree ell-1, so
    zeta_ell in K iff ell-1 == 1 iff ell == 2 (and zeta_2 = -1 lies in Q_2)."""
    return {ell: (ell - 1 == 1) for ell in [2, 3, 5, 7, 11]}

if __name__ == "__main__":
    ch, fl, ex = c1()
    print(f"C1 Lemma 2.1 admissibility of (EK/E, theta o Nr): checked {ch} admissible theta, failures {fl}, examples {ex}")
    print(f"C2 gcd(f,ell)!=1 with ell not| f: {c2()} (empty => Mackey single double coset)")
    print(f"C3 norm-exponent == ell mod (q^f-1) failures: {c3()}")
    r = c4c5()
    for k, v in r.items():
        print(f"C4/C5 exact Tate groups of rank-1 line, ell={k[0]}, sigma acts by {k[1]:+d}: H^0={v[0]}, H^1={v[1]}")
    print(f"C5 nontrivial ell-th root of unity in K=Q_ell^ur?  {c5_roots_of_unity()}")
    print("C5 => Lemma 3.2 'extends uniquely' holds for ell odd, FAILS for ell=2 (c=-1): the sign-twisted\n"
          "     extension swaps Tate groups: H^0(sigma,L_Pi)=0, H^1(sigma,L_Pi)=r_ell(pi)^(ell).")
